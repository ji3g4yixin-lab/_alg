# 求解方程式 x^2 + x - 2 = 0 
# 將方程式改寫為 x = g(x) 的形式來進行迭代

# 方法 1: 將方程式提出 x，得 x(x + 1) = 2，移項得 x = 2 / (x + 1)
f1 = lambda x: 2 / (x + 1)

# 方法 2: 將方程式移項得 x^2 = 2 - x，開根號得 x = (2 - x)**0.5
f2 = lambda x: (2 - x)**0.5

# 方法 3: 使用牛頓-拉弗森法 (Newton-Raphson) 
# f(x) = x^2 + x - 2, f'(x) = 2x + 1
# 迭代公式為 x = x - f(x) / f'(x)
f3 = lambda x: x - (x**2 + x - 2) / (2 * x + 1)

# 設定初始猜測值 (方程式的根為 1 和 -2，這裡設定初始值為 0.5 來逼近 1)
x1 = x2 = x3 = 0.5

for i in range(20):
    x1, x2, x3 = f1(x1), f2(x2), f3(x3)
    print(f'迭代 {i+1:2d}: x1: {x1:.6f}, x2: {x2:.6f}, x3: {x3:.6f}')